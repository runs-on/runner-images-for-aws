#!/bin/bash
# Writes the Dockerfile of a full image to stdout: the provisioners of
# patches/ubuntu/templates/ubuntu-full-<arch>.pkr.hcl, in their order, one
# RUN each so that a failed build resumes from the cache.
#
# Usage: gen-dockerfile.sh IMAGE_ID   (ubuntu26-full-x64 or ubuntu26-full-arm64)
set -euo pipefail
id=$1
repo=$(cd "$(dirname "$0")/../../.." && pwd)
case $id in
  ubuntu26-full-x64) toolset=toolset-2604.json ;;
  ubuntu26-full-arm64) toolset=toolset-2604-arm64.json ;;
  *) echo "unsupported image: $id" >&2; exit 1 ;;
esac
mapfile -t scripts < <(yq -r ".images[] | select(.id == \"$id\") | .install_scripts[]" "$repo/config.yml")
[[ ${#scripts[@]} -gt 0 ]] || { echo "no install_scripts for $id" >&2; exit 1; }

here=$(cd "$(dirname "$0")" && pwd)
B=ubuntu/scripts/build C=ubuntu/custom/files
# One RUN for the given scripts (paths in the build context). Each is
# bind-mounted with its edits, so that changing one script or its edits only
# rebuilds from its own step.
step() {
  local env="" pwsh="" m="--mount=type=bind,source=oci/step.sh,target=/oci/step.sh" args="" f n
  [[ $1 == *=* ]] && { env="$1 "; shift; }
  [[ $1 == pwsh ]] && { pwsh="pwsh "; shift; }
  for f in "$@"; do
    n=${f##*/}
    m+=" --mount=type=bind,source=$f,target=/oci/s/$n"
    [[ -f $here/patches/$n ]] && m+=" --mount=type=bind,source=oci/patches/$n,target=/oci/p/$n"
    args+=" /oci/s/$n"
  done
  echo "RUN $m \\"
  echo "    ${env}/oci/step.sh $pwsh${args# }"
}

cat <<EOF
# Generated by tools/oci2ami/full/gen-dockerfile.sh $id: do not edit.
FROM scratch AS base
# Canonical's cloud image root, the root of the AMI the packer build starts from.
ADD root.tar.xz /

FROM base
SHELL ["/bin/bash", "-c"]
ARG IMAGE_VERSION
ENV PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin:/snap/bin \\
    HOME=/root \\
    DEBIAN_FRONTEND=noninteractive \\
    IMAGE_OS=ubuntu26 \\
    IMAGE_VERSION=\${IMAGE_VERSION} \\
    IMAGE_FOLDER=/imagegeneration \\
    IMAGEDATA_FILE=/imagegeneration/imagedata.json \\
    HELPER_SCRIPTS=/imagegeneration/helpers \\
    HELPER_SCRIPT_FOLDER=/imagegeneration/helpers \\
    INSTALLER_SCRIPT_FOLDER=/imagegeneration/installers \\
    ROLAUNCH_SOURCE=/imagegeneration/installers/rolaunch

COPY oci/shims/ /opt/oci-build/shims/
COPY --from=base /etc/hosts /etc/oci2ami/hosts
RUN /opt/oci-build/shims/enter.sh

COPY ubuntu/custom/files/install-runs-on-bootstrap.sh /tmp/install-runs-on-bootstrap.sh
EOF
step "$C/pre.sh"
cat <<EOF
COPY ubuntu/custom/files/waagent.conf /etc/waagent.conf
RUN mkdir -p /imagegeneration && chmod 777 /imagegeneration
COPY ubuntu/scripts/helpers/ /imagegeneration/helpers/
EOF
step "$B/configure-apt-mock.sh"
step "$B/install-ms-repos.sh" "$B/configure-apt.sh" "$B/configure-dpkg-eatmydata.sh" "$B/configure-apt-gzip-indexes.sh"
step "$B/configure-limits.sh"
cat <<EOF
COPY ubuntu/scripts/build/ /imagegeneration/installers/
COPY rolaunch /imagegeneration/installers/rolaunch
COPY ubuntu/assets/post-gen/ /imagegeneration/post-generation/
COPY ubuntu/scripts/tests/ /imagegeneration/tests/
COPY ubuntu/scripts/docs-gen/ /imagegeneration/SoftwareReport/
COPY software-report-base/ /imagegeneration/SoftwareReport/software-report-base/
COPY ubuntu/toolsets/$toolset /imagegeneration/installers/toolset.json
EOF
step "$B/configure-image-data.sh"
step "$B/configure-environment.sh"
step "$B/install-apt-vital.sh"
step "$B/install-powershell.sh"
step pwsh "$B/Install-PowerShellModules.ps1"
for s in "${scripts[@]}"; do step "$B/$s"; done
step DOCKERHUB_PULL_IMAGES=NO "$B/install-docker.sh"
step pwsh "$B/Install-Toolset.ps1" "$B/Configure-Toolset.ps1"
step "$C/prune-vulnerable-leftovers.sh"
step "$B/configure-snap.sh"
step oci/canonical-ami.sh
step "$C/runner-user.sh"
echo "# The packer build reboots here."
step "$B/cleanup.sh"
step "$B/configure-system.sh" "$C/after-reboot.sh" "$C/configure-syn-reroll.sh" "$C/configure-full-rolaunch.sh"
echo "# prepare-direct-uefi.sh is replaced by the converter's unified kernel image."
step "$C/finalize-runner-environment.sh"
cat <<'EOF'
# Docker replaces /etc/hosts and /etc/resolv.conf in every container: the
# converter installs the copies kept in /etc/oci2ami.
RUN /opt/oci-build/shims/leave.sh && rm -rf /opt/oci-build /tmp/* /root/.cache
EOF
